// Run after build:embed in the committed authoritative source checkout.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, readFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const [sourceArgument, expectedCommit] = process.argv.slice(2)
if (!sourceArgument || !/^[a-f0-9]{40}$/.test(expectedCommit ?? '')) {
  throw new Error('Usage: node scripts/sync-yuanstar-embed.mjs <source checkout> <committed SHA>')
}
const source = resolve(sourceArgument)
const git = (...args) => execFileSync('git', ['-C', source, ...args], { encoding: 'utf8' }).trim()
if (git('rev-parse', 'HEAD') !== expectedCommit) throw new Error('Source HEAD differs from the approved commit')
if (git('status', '--porcelain')) throw new Error('Source must be clean; commit source before release sync')
const branch = git('branch', '--show-current')
const built = join(source, 'web', 'dist', 'embed')
const target = join(root, 'public', 'yuanstar-embed')
const files = (directory, prefix = '') => readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
  const path = prefix + entry.name
  if (entry.isDirectory()) return files(join(directory, entry.name), path + '/')
  if (!entry.isFile()) throw new Error('Unexpected non-file embed entry: ' + path)
  return [path]
}).sort()
const paths = files(built)
// The reviewed Vite worker rename is the only automatic resource-set transition.
const oldPaths = files(target)
const added = paths.filter(path => !oldPaths.includes(path))
const removed = oldPaths.filter(path => !paths.includes(path))
const workerPath = /^assets\/browser-vision-worker-[A-Za-z0-9_-]+\.js$/
if (added.length || removed.length) {
  if (added.length !== 1 || removed.length !== 1 || !workerPath.test(added[0]) || !workerPath.test(removed[0])) throw new Error('Embed resource set changed beyond the reviewed single worker rename')
}
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
const hashes = {}
for (const path of paths) {
  const original = readFileSync(join(built, path))
  copyFileSync(join(built, path), join(target, path))
  const copied = readFileSync(join(target, path))
  if (!original.equals(copied)) throw new Error('Embed byte mismatch: ' + path)
  hashes[path] = hash(copied)
}
if (git('rev-parse', 'HEAD') !== expectedCommit || git('status', '--porcelain')) throw new Error('Source changed during sync')
for (const path of removed) rmSync(join(target,path))
if (JSON.stringify(files(target)) !== JSON.stringify(paths)) throw new Error('Synced embed resource set differs from build')
writeFileSync(join(root, 'docs', 'yuanstar-embed-manifest.json'), JSON.stringify({
  _comment: 'Committed authoritative source; generated by build:embed and full byte-verified sync.',
  _sourceCommit: expectedCommit,
  _sourceBranch: branch,
  _sourceWorkingTree: { status: 'clean' },
  ...hashes,
}, null, 2) + '\n', 'utf8')
console.log(`Synced ${paths.length} embed files; bytes/SHA-256 match committed source ${expectedCommit}`)

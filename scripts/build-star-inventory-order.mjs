// Generates src/data/starInventoryOrder.js from the current YuanStar default
// inventory comparator. Run from the YuanHub repository root:
//   node scripts/build-star-inventory-order.mjs <path-to-YuanStar/web/src/business/snapshot.ts> [output-path]
// The source checks intentionally fail when YuanStar's comparator changes, so
// the generated adapter cannot silently become a separately maintained order.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '..')
const sourcePath = process.argv[2]
const requestedOutputPath = process.argv[3]

if (!sourcePath) {
  throw new Error('Usage: node scripts/build-star-inventory-order.mjs <path-to-YuanStar/web/src/business/snapshot.ts> [output-path]')
}

const source = readFileSync(sourcePath, 'utf8')
const kindMatch = source.match(/const kindOrder(?:\s*:[^=]+)?\s*=\s*(\{[^;]+\})\s*;/)
const qualityMatch = source.match(/const qualityOrder(?:\s*:[^=]+)?\s*=\s*(\{[^;]+\})\s*;/)
if (!kindMatch || !qualityMatch) {
  throw new Error('Could not locate YuanStar sortedInventory kind/quality orders')
}

const priorities = [
  'kindOrder[left.kind] - kindOrder[right.kind]',
  'catalog.orderIndex(left.name) - catalog.orderIndex(right.name)',
  'right.level - left.level',
  'qualityOrder[left.quality] - qualityOrder[right.quality]',
  'left.provenance.sourceOrder - right.provenance.sourceOrder',
  '(left.provenance.row ?? -1) - (right.provenance.row ?? -1)',
  '(left.provenance.column ?? -1) - (right.provenance.column ?? -1)',
  'left.starInstanceId.localeCompare(right.starInstanceId)',
]

function normalizedExpression(expression) {
  return expression
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\r\n]*/g, '')
    .replace(/\s+/g, '')
}

function extractSortedInventoryComparator(sourceText) {
  const functionStart = sourceText.search(/function\s+sortedInventory\b/)
  if (functionStart < 0) throw new Error('Could not locate YuanStar sortedInventory()')
  const nextFunction = sourceText.indexOf('\nexport ', functionStart)
  const body = sourceText.slice(functionStart, nextFunction < 0 ? sourceText.length : nextFunction)
  const signature = /\.sort\s*\(\s*\(\s*left\s*,\s*right\s*\)\s*=>\s*\(/.exec(body)
  if (!signature) throw new Error('Could not locate YuanStar sortedInventory() comparator')
  const expressionStart = signature.index + signature[0].length
  let depth = 1
  for (let index = expressionStart; index < body.length; index += 1) {
    const character = body[index]
    if (character === '(') depth += 1
    if (character === ')') depth -= 1
    if (depth === 0) return body.slice(expressionStart, index)
  }
  throw new Error('YuanStar sortedInventory() comparator is unbalanced')
}

const expectedComparator = normalizedExpression(priorities.join(' || '))
const actualComparator = normalizedExpression(extractSortedInventoryComparator(source))
if (actualComparator !== expectedComparator) {
  throw new Error('YuanStar sortedInventory comparator priority changed; review before regenerating the YuanHub adapter')
}

const kindOrder = JSON.parse(kindMatch[1])
const qualityOrder = JSON.parse(qualityMatch[1])
const output = [
  '// Generated by scripts/build-star-inventory-order.mjs. Do not edit by hand.',
  '// Source: YuanStar web/src/business/snapshot.ts sortedInventory().',
  '// Backend inventory has no provenance fields; absent sourceOrder/row/column',
  '// use the adapter fallbacks below before the same final instanceId tie-break.',
  "import { MAIN_STAR_OPTIONS, ASSIST_STAR_OPTIONS } from './starCatalog.js'",
  '',
  `const SOURCE_KIND_ORDER = Object.freeze(${JSON.stringify(kindOrder)})`,
  `const SOURCE_QUALITY_ORDER = Object.freeze(${JSON.stringify(qualityOrder)})`,
  "const SOURCE_KIND = Object.freeze({ main: '主星', support: '辅星', assist: '辅星' })",
  "const SOURCE_QUALITY = Object.freeze({ orange: '橙', purple: '紫', blue: '蓝', green: '绿', white: '白' })",
  'const CATALOG_ORDER = new Map([...MAIN_STAR_OPTIONS, ...ASSIST_STAR_OPTIONS].map(function (name, index) { return [name, index] }))',
  '',
  'function text(value) { return typeof value === \'string\' ? value.trim() : \'\' }',
  'function number(value, fallback) { return Number.isFinite(Number(value)) ? Number(value) : fallback }',
  'function sourceValue(entry, camel, snake, fallback) {',
  '  const provenance = entry && entry.provenance && typeof entry.provenance === \'object\' ? entry.provenance : {}',
  '  return number(entry && (entry[camel] ?? entry[snake] ?? provenance[camel]), fallback)',
  '}',
  'function instanceId(entry) { return text(entry && (entry.instanceId ?? entry.instance_id ?? entry.starInstanceId ?? entry.id)) }',
  'function kindRank(entry) { return SOURCE_KIND_ORDER[SOURCE_KIND[text(entry && (entry.kind ?? entry.type))] || text(entry && (entry.kind ?? entry.type))] ?? Number.MAX_SAFE_INTEGER }',
  'function catalogRank(entry) { return CATALOG_ORDER.get(text(entry && entry.name)) ?? CATALOG_ORDER.size }',
  'function qualityRank(entry) { const quality = text(entry && entry.quality); return SOURCE_QUALITY_ORDER[SOURCE_QUALITY[quality] || quality] ?? Number.MAX_SAFE_INTEGER }',
  '',
  'export function compareYuanStarInventoryEntries(left, right) {',
  '  return kindRank(left) - kindRank(right)',
  '    || catalogRank(left) - catalogRank(right)',
  '    || number(right && right.level, 0) - number(left && left.level, 0)',
  '    || qualityRank(left) - qualityRank(right)',
  "    || sourceValue(left, 'sourceOrder', 'source_order', 0) - sourceValue(right, 'sourceOrder', 'source_order', 0)",
  "    || sourceValue(left, 'row', 'row', -1) - sourceValue(right, 'row', 'row', -1)",
  "    || sourceValue(left, 'column', 'column', -1) - sourceValue(right, 'column', 'column', -1)",
  '    || instanceId(left).localeCompare(instanceId(right))',
  '}',
  '',
  'export function sortYuanStarInventoryEntries(entries) {',
  '  return Array.isArray(entries) ? [...entries].sort(compareYuanStarInventoryEntries) : []',
  '}',
  '',
].join('\n')

const outputPath = requestedOutputPath || path.join(repoRoot, 'src', 'data', 'starInventoryOrder.js')
writeFileSync(outputPath, output, 'utf8')
console.log('written:', outputPath)

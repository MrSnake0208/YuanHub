// Generates browser-safe usage tags from YuanStar browser catalog descriptions.
// Usage: node scripts/build-star-usage-tags.mjs <descriptions.ts> <star_catalog.json>
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '..')
const [descriptionsPath, catalogPath] = process.argv.slice(2)
if (!descriptionsPath || !catalogPath) throw new Error('Usage: node scripts/build-star-usage-tags.mjs <descriptions.ts> <star_catalog.json>')

const source = readFileSync(descriptionsPath, 'utf8')
const descriptions = Object.fromEntries([...source.matchAll(/^\s*"([^"]+)":\s*"([^"]*)",?$/gm)].map(function (match) {
  return [match[1], match[2].replace(/\\n/g, '\n')]
}))
const catalog = JSON.parse(readFileSync(catalogPath, 'utf8')).stars
if (!Array.isArray(catalog)) throw new Error('Expected YuanStar star_catalog.json stars[]')

const tags = {}
for (const star of catalog) {
  const name = String(star && star.name || '').trim()
  const kind = star && star.kind
  if (kind !== '主星' && kind !== '辅星') continue
  const description = descriptions[name]
  if (!name || !description) throw new Error('Missing browser description for canonical star: ' + name)
  const next = kind === '主星'
    ? ['攻击', '生命'].filter(function (tag) { return description.includes(tag === '攻击' ? '攻击力' : '生命值') })
    : ['增伤', '抗性', '治疗', '免伤'].filter(function (tag) { return description.includes(tag) })
  if (kind === '主星' && !next.length) next.push('其它')
  if (!next.length) throw new Error('Unclassifiable star description: ' + name)
  tags[name] = next
}

const output = [
  '// Generated by scripts/build-star-usage-tags.mjs. Do not edit by hand.',
  '// Source: YuanStar web/src/business/browser-catalog-descriptions.ts.',
  '',
  `export const STAR_USAGE_TAGS = Object.freeze(${JSON.stringify(tags, null, 2)})`,
  '',
  'export function starUsageTags(name) { return STAR_USAGE_TAGS[name] || [] }',
  '',
].join('\n')
writeFileSync(path.join(repoRoot, 'src', 'data', 'starUsageTags.js'), output, 'utf8')

// Generates src/data/starCatalog.js from YuanStar's canonical catalog.
// Usage from the YuanHub repository root:
//   node scripts/build-star-catalog.mjs <path-to-YuanStar/data/star_catalog.json>
// The generated module is vendored for browser runtime use; edit the YuanStar
// source catalog instead of editing the generated output.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '..')
const sourcePath = process.argv[2]

if (!sourcePath) {
  throw new Error('Usage: node scripts/build-star-catalog.mjs <path-to-YuanStar/data/star_catalog.json>')
}

const document = JSON.parse(readFileSync(sourcePath, 'utf8'))
if (!Array.isArray(document.stars)) {
  throw new Error('Expected a YuanStar star_catalog.json document with stars[]')
}

function namesFor(kind) {
  return document.stars
    .filter(function (star) { return star && star.kind === kind && typeof star.name === 'string' && star.name.trim() })
    .map(function (star) { return star.name.trim() })
}

const main = namesFor('主星')
const support = namesFor('辅星')
if (!main.length || !support.length) {
  throw new Error('Canonical catalog must contain both 主星 and 辅星 names')
}

const output = [
  '// Generated by scripts/build-star-catalog.mjs. Do not edit by hand.',
  '// Source: YuanStar data/star_catalog.json (主星 / 辅星 canonical order).',
  '',
  `export const MAIN_STAR_OPTIONS = ${JSON.stringify(main, null, 2)}`,
  '',
  `export const ASSIST_STAR_OPTIONS = ${JSON.stringify(support, null, 2)}`,
  '',
].join('\n')

const outputPath = path.join(repoRoot, 'src', 'data', 'starCatalog.js')
writeFileSync(outputPath, output, 'utf8')
console.log('written:', outputPath)
console.log('main:', main.length, '| support:', support.length)

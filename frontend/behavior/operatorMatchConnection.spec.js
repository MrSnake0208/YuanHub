import { mount, flushPromises } from '@vue/test-utils'
import { describe, it, expect, vi, beforeEach } from 'vitest'
import OperatorMatchConnection from '../src/components/OperatorMatchConnection.vue'
import * as api from '../src/api/operatorMatch.js'
import { dialog } from '../src/utils/dialog.js'

vi.mock('../src/api/operatorMatch.js', () => ({
  listMatchConnections: vi.fn(), createMatchConnection: vi.fn(), getMatchSecret: vi.fn(), revokeMatchConnection: vi.fn()
}))
vi.mock('../src/utils/dialog.js', () => ({ dialog: { confirm: vi.fn() } }))
const item = { connection_id: 'c', created_at: '2026-11-06T00:00:00Z' }
const button = (wrapper, text) => wrapper.findAll('button').find(b => b.text() === text)
beforeEach(() => {
  vi.resetAllMocks()
  api.listMatchConnections.mockResolvedValue([item])
  api.getMatchSecret.mockResolvedValue({ token: 'ymatch_test' })
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: vi.fn().mockResolvedValue() } })
})
describe('independent matching connection', () => {
  it('shows direct actions and copies without displaying the secret', async () => {
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner', enabled: true } })
    await flushPromises()
    expect(api.listMatchConnections).toHaveBeenCalledWith('owner')
    expect(wrapper.get('a').text()).toBe('访问作业站')
    expect(wrapper.find('details').exists()).toBe(false)
    expect(wrapper.text()).not.toContain('读取星石面板')
    expect(wrapper.text()).not.toContain('创建连接需要 YuanHub Beta 资格')
    await button(wrapper, '复制连接码').trigger('click'); await flushPromises()
    expect(api.getMatchSecret).toHaveBeenCalledWith('owner', 'c')
    expect(navigator.clipboard.writeText).toHaveBeenCalledWith('ymatch_test')
    expect(wrapper.text()).toContain('连接码已复制')
    expect(wrapper.find('input').exists()).toBe(false)
    expect(localStorage.length).toBe(0)
  })
  it('creates a connection from the empty state without exposing the token', async () => {
    api.listMatchConnections.mockResolvedValueOnce([]).mockResolvedValue([item])
    api.createMatchConnection.mockResolvedValue({ token: 'ymatch_test', ...item })
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner', enabled: true } })
    await flushPromises()
    await button(wrapper, '添加只读匹配连接').trigger('click'); await flushPromises()
    expect(api.createMatchConnection).toHaveBeenCalledWith('owner')
    expect(button(wrapper, '复制连接码')).toBeDefined()
    expect(wrapper.find('input').exists()).toBe(false)
  })
  it('retains the created connection when refreshing its metadata fails', async () => {
    api.listMatchConnections.mockResolvedValueOnce([]).mockRejectedValueOnce(new Error('刷新失败'))
    api.createMatchConnection.mockResolvedValue({ token: 'ymatch_test', connection_id: 'new' })
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner', enabled: true } })
    await flushPromises()
    await button(wrapper, '添加只读匹配连接').trigger('click'); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBe('刷新失败')
    await button(wrapper, '复制连接码').trigger('click'); await flushPromises()
    expect(api.getMatchSecret).toHaveBeenCalledWith('owner', 'new')
  })
  it('offers manual recovery when clipboard access fails and clears it on user change', async () => {
    navigator.clipboard.writeText.mockRejectedValue(new Error('denied'))
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner' } })
    await flushPromises()
    await button(wrapper, '复制连接码').trigger('click'); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('手动复制')
    expect(wrapper.get('input').attributes('type')).toBe('password')
    await button(wrapper, '显示以手动复制').trigger('click')
    expect(wrapper.get('input').element.value).toBe('ymatch_test')
    expect(wrapper.get('input').attributes('type')).toBe('text')
    await wrapper.setProps({ userId: 'other' }); await flushPromises()
    expect(wrapper.find('input').exists()).toBe(false)
    expect(wrapper.text()).not.toContain('复制失败')
    expect(api.listMatchConnections).toHaveBeenLastCalledWith('other')
  })
  it('does not copy a late secret for a changed user', async () => {
    let resolve
    api.getMatchSecret.mockImplementation(() => new Promise(done => { resolve = done }))
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner' } })
    await flushPromises()
    await button(wrapper, '复制连接码').trigger('click')
    await wrapper.setProps({ userId: 'other' })
    resolve({ token: 'private' }); await flushPromises()
    expect(navigator.clipboard.writeText).not.toHaveBeenCalled()
    expect(wrapper.find('input').exists()).toBe(false)
  })
  it('revokes only after confirmation and returns to the empty state', async () => {
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner' } })
    await flushPromises()
    dialog.confirm.mockResolvedValue(false)
    await button(wrapper, '停止连接').trigger('click'); await flushPromises()
    expect(api.revokeMatchConnection).not.toHaveBeenCalled()
    dialog.confirm.mockResolvedValue(true)
    api.revokeMatchConnection.mockResolvedValue(null)
    await button(wrapper, '停止连接').trigger('click'); await flushPromises()
    expect(api.revokeMatchConnection).toHaveBeenCalledWith('owner', 'c')
    expect(wrapper.text()).toContain('连接已停止')
    expect(wrapper.findAll('.match-control-row')).toHaveLength(0)
  })
  it('shows only the oldest legacy connection and no extra creation action', async () => {
    api.listMatchConnections.mockResolvedValue([{ ...item, connection_id: 'newer' }, item])
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner', enabled: true } })
    await flushPromises()
    expect(wrapper.findAll('.match-control-row')).toHaveLength(1)
    expect(button(wrapper, '添加只读匹配连接')).toBeUndefined()
    await button(wrapper, '复制连接码').trigger('click'); await flushPromises()
    expect(api.getMatchSecret).toHaveBeenCalledWith('owner', 'c')
  })
  it('keeps failed loading distinct from an empty list and supports retry', async () => {
    api.listMatchConnections.mockRejectedValueOnce(new Error('加载失败'))
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner', enabled: true } })
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBe('加载失败')
    expect(button(wrapper, '添加只读匹配连接')).toBeUndefined()
    await button(wrapper, '重新加载连接').trigger('click'); await flushPromises()
    expect(button(wrapper, '复制连接码')).toBeDefined()
  })
  it('disables creation without beta access while retaining existing connection actions', async () => {
    const wrapper = mount(OperatorMatchConnection, { props: { userId: 'owner', enabled: false } })
    await flushPromises()
    expect(button(wrapper, '添加只读匹配连接')).toBeUndefined()
    expect(button(wrapper, '复制连接码').element.disabled).toBe(false)
    expect(button(wrapper, '停止连接').element.disabled).toBe(false)
  })
})

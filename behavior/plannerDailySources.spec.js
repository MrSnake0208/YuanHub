it.each(['preview', 'account', 'plan', 'revision', 'date', 'overwrite'])('确认期间%s变化，旧确认不再应用日程', async change => {
  let answer
  dialog.confirm.mockImplementationOnce(() => new Promise(resolve => { answer = resolve }))
  const wrapper = setup({ preview }); wrapper.get('.source-application-region').element.open = true
  await button(wrapper, '应用到未来日程').trigger('click')
  if (change === 'date') await wrapper.get('[aria-label="固定来源应用开始日期"]').setValue('2026-10-20')
  else if (change === 'overwrite') await wrapper.get('.overwrite-option input').setValue(true)
  else await wrapper.setProps(change === 'preview' ? { preview: { ...preview, affectedDates: 8 } } : change === 'account' ? { accountId: 'b' } : change === 'revision' ? { revision: 2 } : { planId: 'other' })
  answer(true); await flushPromises()
  expect(wrapper.emitted('apply')).toBeUndefined()
})


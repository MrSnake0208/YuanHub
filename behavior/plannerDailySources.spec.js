it('保存摘要依据有效期与启用状态，月卡未启用时不会把商店数值当有效权益', async () => {
  const sources = emptyStaminaSources()
  Object.assign(sources.monthlyCard, { dailyEnabled: true, shopEnabled: true, dailyAmount: 60, shopAmount: 19 })
  sources.fixedSources = [{ id: 'event', label: '活动奖励', value: 37, enabled: true }, { id: 'gift', label: '礼包', value: 123, enabled: false }]
  const wrapper = setup({ sources })
  expect(wrapper.findAll('.condition-summary-card')[0].text()).toContain('未启用月卡')
  expect(wrapper.findAll('.condition-summary-card')[0].text()).toContain('每日奖励 0 · 商店预计领取 0')
  expect(wrapper.findAll('.condition-summary-card')[1].text()).toContain('已启用 1 项 · 合计 37 体力/日')
  expect(wrapper.text()).toContain('另有 1 项已停用')
  const withCard = { ...sources, monthlyCard: { ...sources.monthlyCard, tier: 'custom', startDate: '2026-10-17', endDate: '2026-10-17' } }
  await wrapper.setProps({ sources: withCard, revision: 2 })
  expect(wrapper.findAll('.condition-summary-card')[0].text()).toContain('每日奖励 60 · 商店预计领取 19')
  await wrapper.setProps({ today: '2026-10-18' })
  expect(wrapper.findAll('.condition-summary-card')[0].text()).toContain('已过期')
  expect(wrapper.findAll('.condition-summary-card')[0].text()).toContain('每日奖励 0 · 商店预计领取 0')
  await wrapper.setProps({ today: '2026-10-16' })
  expect(wrapper.findAll('.condition-summary-card')[0].text()).toContain('2026-10-17 起生效')
  expect(wrapper.emitted('save')).toBeUndefined()
})


it('日期、数值与名称校验保留；预览携带替换规则，应用必须先预览再确认', async () => {
  const wrapper = setup()
  expect(button(wrapper, '应用到未来日程').element.disabled).toBe(true)
  await open(wrapper)
  await wrapper.get('[aria-label="月卡每日奖励体力"]').setValue(-1); await save(wrapper)
  expect(wrapper.emitted('save')).toBeUndefined()
  await wrapper.get('[aria-label="月卡每日奖励体力"]').setValue(0)
  await wrapper.get('[aria-label="月卡生效日期"]').setValue('2026-10-18')
  await wrapper.get('[aria-label="月卡有效至"]').setValue('2026-10-17'); await save(wrapper)
  expect(wrapper.get('[role="alert"]').text()).toContain('月卡生效日期范围')
  expect(wrapper.emitted('save')).toBeUndefined()
  await button(wrapper, '取消').trigger('click'); await flushPromises()
  wrapper.get('.source-application-region').element.open = true
  await wrapper.get('.overwrite-option input').setValue(true)
  await wrapper.get('[aria-label="固定来源应用开始日期"]').setValue('2026-10-20')
  await button(wrapper, '查看将修改的日程').trigger('click')
  expect(wrapper.emitted('preview').at(-1)).toEqual([{ fromDate: '2026-10-20', overwrite: true }])
  expect(wrapper.emitted('apply')).toBeUndefined()
  await wrapper.setProps({ preview: { ...preview, fromDate: '2026-10-20' } })
  dialog.confirm.mockResolvedValueOnce(false)
  await button(wrapper, '应用到未来日程').trigger('click'); await flushPromises()
  expect(wrapper.emitted('apply')).toBeUndefined()
  await wrapper.setProps({ accountId: 'b', revision: 0, selectedDate: '2026-10-16' })
  expect(wrapper.get('[aria-label="固定来源应用开始日期"]').element.value).toBe('2026-10-17')
  expect(wrapper.get('.overwrite-option input').element.checked).toBe(false)
})


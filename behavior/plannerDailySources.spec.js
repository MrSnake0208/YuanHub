it('固定来源的无效数值会重新展开所属卡片与编辑行，允许定位并修正', async () => {
  installViewport(390)
  const sources = emptyStaminaSources()
  sources.fixedSources = [{ id: 'event', label: '活动', value: 37, enabled: true }]
  const wrapper = setup({ sources })
  await wrapper.get('[aria-controls="fixed-sources-editor"]').trigger('click')
  const edit = wrapper.get('[aria-label="编辑固定来源活动"]')
  await edit.trigger('click')
  const amount = wrapper.get('[aria-label="固定来源每日体力1"]')
  await amount.setValue(-1)
  await edit.trigger('click')
  await wrapper.get('[aria-controls="fixed-sources-editor"]').trigger('click')
  expect(edit.attributes('aria-expanded')).toBe('false')
  expect(amount.element.checkValidity()).toBe(false)
  await flushPromises()
  expect(wrapper.get('[aria-controls="fixed-sources-editor"]').attributes('aria-expanded')).toBe('true')
  expect(edit.attributes('aria-expanded')).toBe('true')
  expect(wrapper.get('.fixed-source-row').isVisible()).toBe(true)
  await amount.setValue(37)
  expect(amount.element.checkValidity()).toBe(true)
})

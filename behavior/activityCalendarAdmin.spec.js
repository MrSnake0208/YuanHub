import { beforeEach, expect, it, vi } from 'vitest'
import { flushPromises, mount, RouterLinkStub } from '@vue/test-utils'
import Admin from '../src/pages/calendar/admin.vue'
import * as api from '../src/api/activityCalendar.js'
import { auth } from '../src/store/auth.js'
import { dialog } from '../src/utils/dialog.js'
import { isFeatureEnabled } from '../src/config/features.js'
import { getVisibleAdminTools } from '../src/utils/adminTools.js'

vi.mock('../src/store/auth.js', async () => ({ auth: (await import('vue')).reactive({ accessToken: 'synthetic', userInfo: { id: 'admin-a' }, adminAccess: { permissions: ['activity_calendar:write'] } }) }))
vi.mock('vue-router', () => ({ onBeforeRouteLeave: vi.fn(), onBeforeRouteUpdate: vi.fn() }))
vi.mock('../src/utils/dialog.js', () => ({ dialog: { confirm: vi.fn() } }))
vi.mock('../src/config/features.js', async importOriginal => ({ ...(await importOriginal()), isFeatureEnabled: vi.fn(() => true) }))
vi.mock('../src/api/activityCalendar.js', () => ({ listAdminActivityCalendar: vi.fn(), createActivityCalendar: vi.fn(), updateActivityCalendar: vi.fn() }))
const item = (patch = {}) => ({ id: 'evt-a', title: '手工活动', game: '如鸢', category: 'ACTIVITY', start_date: '2026-10-03', end_date: '2026-10-10', source_type: 'MANUAL', ...patch })
const entry = (patch = {}) => ({ item: item(), version: 0, enabled: true, read_only: false, source_note: '整理备注', updated_at: '2026-10-03T10:00:00Z', ...patch })
const render = () => mount(Admin, { attachTo: document.body, global: { stubs: { IslandSidebar: true, SiteFooter: true, AdminBackLink: true, RouterLink: RouterLinkStub } } })
const button = (wrapper, text) => wrapper.findAll('button').find(node => node.text() === text)
const filter = (wrapper, label) => wrapper.findAll('label').find(node => node.text().startsWith(label)).find('input, select')
function deferred() { let resolve; const promise = new Promise(r => { resolve = r }); return { promise, resolve } }
beforeEach(() => {
  vi.clearAllMocks(); isFeatureEnabled.mockReturnValue(true); dialog.confirm.mockResolvedValue(true)
  auth.accessToken = 'synthetic'; auth.userInfo = { id: 'admin-a' }; auth.adminAccess = { permissions: ['activity_calendar:write'] }
  api.listAdminActivityCalendar.mockResolvedValue({ items: [entry()] })
  api.createActivityCalendar.mockResolvedValue(entry()); api.updateActivityCalendar.mockResolvedValue(entry({ version: 1 }))
})

it('缺权限或关闭flag时不读写管理员API，也不暴露管理工具', async () => {
  auth.adminAccess = { permissions: [] }
  const wrapper = render(); await flushPromises()
  expect(wrapper.text()).toContain('需要活动日历维护权限')
  expect(api.listAdminActivityCalendar).not.toHaveBeenCalled()
  expect(getVisibleAdminTools(auth.adminAccess)).toEqual([])
  wrapper.unmount()
  auth.adminAccess = { permissions: ['activity_calendar:write'] }; isFeatureEnabled.mockReturnValue(false)
  render(); await flushPromises()
  expect(api.listAdminActivityCalendar).not.toHaveBeenCalled()
  expect(getVisibleAdminTools(auth.adminAccess)).toEqual([])
  expect(api.createActivityCalendar).not.toHaveBeenCalled()
  expect(api.updateActivityCalendar).not.toHaveBeenCalled()
})
it('列表筛选提交API，独立编辑器与列表互斥，保存携带version=0并保留筛选', async () => {
  const wrapper = render(); await flushPromises()
  await filter(wrapper, '游戏').setValue('如鸢')
  await filter(wrapper, '类型').setValue('ACTIVITY')
  await filter(wrapper, '启用状态').setValue('true')
  await filter(wrapper, '日期范围起点').setValue('2026-10-01')
  await filter(wrapper, '日期范围终点').setValue('2026-10-15')
  await filter(wrapper, '搜索标题').setValue('活动')
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(api.listAdminActivityCalendar.mock.lastCall[0]).toEqual({ game: '如鸢', category: 'ACTIVITY', enabled: 'true', from: '2026-10-01', to: '2026-10-15', search: '活动' })
  await button(wrapper, '编辑活动').trigger('click')
  expect(wrapper.find('.calendar-list').exists()).toBe(false)
  expect(document.activeElement).toBe(wrapper.get('.calendar-editor').element)
  expect(wrapper.get('#calendar-category').text()).not.toContain('招募')
  await wrapper.get('#calendar-title').setValue('修改后的活动')
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(api.updateActivityCalendar).toHaveBeenCalledWith('evt-a', expect.objectContaining({ expected_version: 0, title: '修改后的活动', source_note: '整理备注', enabled: true }))
  expect(wrapper.find('.calendar-editor').exists()).toBe(false)
  expect(filter(wrapper, '搜索标题').element.value).toBe('活动')
  expect(wrapper.text()).toContain('活动已保存')
})

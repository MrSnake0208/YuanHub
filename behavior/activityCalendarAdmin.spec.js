  expect(wrapper.get('[role=alert]').text()).toContain('内容已被其他人修改，请刷新后重试')
  expect(document.activeElement).toBe(wrapper.get('[role=alert]').element)
  expect(button(wrapper, '保存活动').element.disabled).toBe(true)
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(api.updateActivityCalendar).toHaveBeenCalledTimes(1)

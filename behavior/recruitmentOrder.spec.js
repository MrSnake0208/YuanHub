import { expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import { dialog } from '../src/utils/dialog.js'
import PoolEditor from '../src/pages/recruitment/PoolEditor.vue'
import { recruitmentCatalog, recruitmentEvent, recruitmentFixture } from '../test-support/recruitment.js'
const records = () => [
  { ...recruitmentEvent('A', 17), agent_snapshot: { agent_id: 'a', name: '杨修', rarity: 5 } },
  { ...recruitmentEvent('B', null), agent_snapshot: { agent_id: 'b', name: '郭嘉', rarity: 5 } },
]
const render = props => mount(PoolEditor, { attachTo: document.body, props: { open: true, pool: recruitmentFixture().pools[0], recordsRevision: 3, records: records(), canRecord: true, catalog: recruitmentCatalog().pools, agents: [{ id: 'a', name: '杨修', rarity: 5, pinyin: 'yangxiu' }, { id: 'b', name: '郭嘉', rarity: 5 }, { id: 'lu', name: '陆逊', rarity: 5 }], ...props }, global: { stubs: { Teleport: true } } })
const button = (w, text) => w.findAll('button').find(b => b.text() === text)
async function position(w, mode, anchor) {
  await w.get('.position-toggle').trigger('click')
  await w.get('.position-picker select').setValue(mode)
  if (anchor) await w.findAll('.position-picker select')[1].setValue(anchor)
}
async function addLu(w) {
  await w.get('.add-record').trigger('click')
  await w.get('.agent-choice[data-agent-id="lu"]').trigger('click')
}
const pulls = w => w.findAll('.record-detail .pull-result b').map(b => b.text())
it.each([
  ['before', 'B', ['A', 'new', 'B']], ['after', 'A', ['A', 'new', 'B']],
  ['earliest', null, ['new', 'A', 'B']], ['latest', null, ['A', 'B', 'new']],
])('补录陆逊选择%s，保留未知间隔及保底，双视图共享顺序', async (mode, anchor, expected) => {
  const w = render()
  await addLu(w)
  await w.get('.pull-count-field input').setValue('20')
  await position(w, mode, anchor)
  expect(w.get('.position-picker legend').text()).toContain('最早 → 最新')
  await w.get('.composer-actions .primary').trigger('click')
  await w.get('form').trigger('submit')
  const payload = w.emitted('save')[0][0], id = payload.data.entries[0].event_id
  const ids = expected.map(value => value === 'new' ? id : value)
  expect(payload.data.ordered_event_ids || ['A', 'B', id]).toEqual(ids)
  expect(payload.data.entries).toEqual([{ event_id: id, agent_id: 'lu', pull_span: 20, up_status: 'unknown', acquired_date: null, note: null }])
  expect(payload.data.remaining_pulls).toBe(40)
  expect(pulls(w)).toEqual(ids.slice().reverse().map(value => value === id ? '20' : value === 'A' ? '17' : '未知'))
  await button(w, '密探视图').trigger('click')
  expect(w.findAll('.agent-record-detail').map(b => b.attributes('aria-label').split('，')[0])).toEqual(ids.slice().reverse().map(value => '编辑' + (value === id ? '陆逊' : value === 'A' ? '杨修' : '郭嘉')))
  await w.get('form').trigger('submit')
  expect(w.emitted('save')[1][0].requestId).toBe(payload.requestId)
  w.unmount()
})
it('旧记录纯排序，拼音搜索不缩减参照记录，取消不改草稿', async () => {
  const w = render()
  await w.get('.record-search input').setValue('yangxiu')
  expect(w.findAll('.record-detail')).toHaveLength(1)
  await w.get('.record-detail').trigger('click')
  await position(w, 'after', 'B')
  expect(w.findAll('.position-picker select')[1].text()).toContain('郭嘉')
  await button(w, '取消').trigger('click')
  expect(w.vm.hasDraft()).toBe(false)
  await w.get('.record-detail').trigger('click')
  await position(w, 'after', 'B')
  await w.get('.composer-actions .primary').trigger('click')
  expect(w.vm.hasDraft()).toBe(true)
  await w.get('form').trigger('submit')
  expect(w.emitted('save')[0][0].data).toEqual({ pool_id: 'pool-a', entries: [], deleted_event_ids: [], remaining_pulls: 40, ordered_event_ids: ['B', 'A'] })
  w.unmount()
})
it('分页未完先请求全量，缺失锚点保留草稿', async () => {
  const w = render({ records: records().slice(0, 1), hasMore: true })
  await addLu(w)
  await w.get('.position-toggle').trigger('click')
  expect(w.emitted('load-all')).toHaveLength(1)
  expect(w.get('.position-picker select').element.disabled).toBe(true)
  await w.setProps({ records: records(), hasMore: false })
  await w.get('.position-picker select').setValue('before')
  await w.findAll('.position-picker select')[1].setValue('B')
  await w.setProps({ records: records().slice(0, 1), recordsRevision: 4 })
  await w.get('.composer-actions .primary').trigger('click')
  expect(w.text()).toContain('参照记录已删除或不可用')
  expect(w.find('.entry-composer').exists()).toBe(true)
  expect(w.emitted('save')).toBeUndefined()
  w.unmount()
})
it('回执核验完整权威顺序，错误顺序及回读失败不清草稿', async () => {
  const w = render()
  await w.findAll('.record-detail')[1].trigger('click')
  await position(w, 'after', 'B')
  await w.get('.composer-actions .primary').trigger('click')
  await w.get('form').trigger('submit')
  const receipt = { ...w.emitted('save')[0][0].data, revision: 4 }
  await w.setProps({ saveReceipt: receipt, recordsRevision: 4, recordsError: '离线' })
  expect(w.find('.save-result.is-confirmed').exists()).toBe(false)
  expect(w.vm.hasDraft()).toBe(true)
  await w.setProps({ recordsError: '', records: records() })
  expect(w.find('.save-result.is-confirmed').exists()).toBe(false)
  await w.setProps({ records: records().reverse(), hasMore: true })
  expect(w.find('.save-result.is-confirmed').exists()).toBe(false)
  await w.setProps({ hasMore: false })
  await flushPromises()
  expect(w.find('.save-result.is-confirmed').exists()).toBe(true)
  expect(w.vm.hasDraft()).toBe(false)
  expect(w.get('.save-result strong').text()).toContain('历史顺序已保存')
  expect(pulls(w)).toEqual(['17', '未知'])
  w.unmount()
})
it('409保留排序草稿并阻止未经核对重提，未知保底可纯排序', async () => {
  const w = render({ pool: { ...recruitmentFixture().pools[0], progress: null } })
  await w.findAll('.record-detail')[1].trigger('click')
  await position(w, 'latest')
  await w.get('.composer-actions .primary').trigger('click')
  await w.get('form').trigger('submit')
  expect(w.emitted('save')[0][0].data.remaining_pulls).toBeNull()
  await w.setProps({ recordsRevision: 4, serverError: '409，请核对', requestVersion: 1 })
  await w.get('form').trigger('submit')
  expect(w.emitted('save')).toHaveLength(1)
  expect(w.text()).toContain('顺序草稿已保留')
  expect(w.vm.hasDraft()).toBe(true)
  w.unmount()
})

it('409后远端删除锚点可明确放弃失效行、保留新增和编辑草稿并重新排序保存', async () => {
  const w = render()
  await w.findAll('.record-detail')[1].trigger('click')
  await w.get('.pull-count-field input').setValue('18')
  await w.get('.composer-actions .primary').trigger('click')
  await addLu(w)
  await position(w, 'before', 'B')
  await w.get('.composer-actions .primary').trigger('click')
  await w.get('form').trigger('submit')
  const newId = w.emitted('save')[0][0].data.entries.find(e => e.agent_id === 'lu').event_id
  await w.setProps({ records: records().slice(0, 1), recordsRevision: 4, serverError: '409', requestVersion: 1 })
  expect(w.text()).toContain('有 1 笔旧记录已在其他设备移除')
  const confirm = vi.spyOn(dialog, 'confirm').mockResolvedValueOnce(false)
  await button(w, '核对失效草稿').trigger('click'); await flushPromises()
  expect(w.findAll('.record-detail')).toHaveLength(3)
  confirm.mockResolvedValueOnce(true)
  await button(w, '核对失效草稿').trigger('click'); await flushPromises()
  expect(w.findAll('.record-detail')).toHaveLength(2)
  await w.findAll('.record-detail').find(b => b.attributes('aria-label').includes('陆逊')).trigger('click')
  await position(w, 'earliest')
  await w.get('.composer-actions .primary').trigger('click')
  await w.get('form').trigger('submit')
  const data = w.emitted('save')[1][0].data
  expect(data.ordered_event_ids).toEqual([newId, 'A'])
  expect(data.deleted_event_ids).toEqual([])
  expect(data.entries.find(e => e.event_id === 'A').pull_span).toBe(18)
  expect(data.entries.find(e => e.event_id === newId).pull_span).toBeNull()
  confirm.mockRestore(); w.unmount()
})
it.each(['已抽', '已垫'])('未知保底纯排序兼容%s偏好，排序草稿关闭提醒且键盘焦点进入选择框', async mode => {
  const w = render({ pool: { ...recruitmentFixture().pools[0], progress: null } })
  await button(w, mode).trigger('click')
  await w.findAll('.record-detail')[1].trigger('click')
  await w.get('.position-toggle').trigger('click')
  await flushPromises()
  expect(document.activeElement).toBe(w.get('.position-picker select').element)
  await w.get('.position-picker select').setValue('latest')
  const confirm = vi.spyOn(dialog, 'confirm').mockResolvedValue(false)
  await w.get('.close-button').trigger('click'); await flushPromises()
  expect(confirm).toHaveBeenCalledOnce()
  expect(w.find('.position-picker').exists()).toBe(true)
  await w.get('.composer-actions .primary').trigger('click')
  await w.get('form').trigger('submit')
  expect(w.emitted('save')[0][0].data).toMatchObject({ remaining_pulls: null, entries: [], ordered_event_ids: ['B', 'A'] })
  confirm.mockRestore(); w.unmount()
})

it('领取清单就地提示超限，修正后恢复联合预计结果及确认按钮', async () => {
  getMailboxReserve.mockResolvedValue({ ...record('a', 199), fu_chuan_mail_count: 2312 })
  await open(false)
  await button('记录领取').trigger('click')
  expect(wrapper.get('.mail-claim-totals').text()).toBe('0 白金币 · 0 符传')
  const coins = () => input('第1组白金币邮件本次领取封数')
  const tickets = () => input('符传邮件本次领取封数')
  await coins().setValue('200')
  expect(coins().element.value).toBe('200')
  expect(wrapper.get(`[id="${coins().attributes('aria-describedby')}"]`).text()).toContain('最多可领取 199 封，当前多填了 1 封')
  expect(wrapper.get('.mail-claim-totals').text()).toBe('18,000 白金币 · 0 符传')
  expect(button('确认记录领取').element.disabled).toBe(true)
  await coins().setValue('199')
  expect(coins().attributes('aria-invalid')).toBe('false')
  expect(coins().attributes('aria-describedby')).toBeUndefined()
  expect(wrapper.find('.mail-claim-error').exists()).toBe(false)
  expect(wrapper.get('.mail-claim-totals').text()).toBe('17,910 白金币 · 0 符传')
  expect(button('确认记录领取').element.disabled).toBe(false)
  await tickets().setValue('2313')
  expect(wrapper.get(`[id="${tickets().attributes('aria-describedby')}"]`).text()).toContain('最多可领取 2312 封，当前多填了 1 封')
  expect(button('确认记录领取').element.disabled).toBe(true)
  await tickets().setValue('1')
  expect(wrapper.find('.mail-claim-error').exists()).toBe(false)
  expect(wrapper.get('.mail-claim-totals').text()).toBe('17,910 白金币 · 3 符传')
  expect(button('确认记录领取').element.disabled).toBe(false)
  expect(claimMailboxReserve).not.toHaveBeenCalled()
})


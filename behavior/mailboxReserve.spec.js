it('报告入口等待初次读取再打开储备，切账号后不打开旧请求', async () => {
  const late = deferred()
  getMailboxReserve.mockReturnValueOnce(late.promise)
  wrapper = mount(MailboxReserve, { props: { userId: 'owner', accountId: 'a' }, global: { stubs: { teleport: true } } })
  const opening = wrapper.vm.openManage()
  expect(wrapper.find('form').exists()).toBe(false)
  late.resolve(record()); await opening; await flushPromises()
  expect(wrapper.find('.mailbox-manage-form').exists()).toBe(true)
  wrapper.unmount()
  const old = deferred()
  getMailboxReserve.mockReturnValueOnce(old.promise).mockResolvedValueOnce(record('b'))
  wrapper = mount(MailboxReserve, { props: { userId: 'owner', accountId: 'a' }, global: { stubs: { teleport: true } } })
  const oldOpening = wrapper.vm.openManage()
  await wrapper.setProps({ accountId: 'b' }); await flushPromises()
  old.resolve(record()); await oldOpening; await flushPromises()
  expect(wrapper.find('form').exists()).toBe(false)
})

import { mount, flushPromises } from '@vue/test-utils'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import MailboxReserve from '../src/components/inventory/MailboxReserve.vue'
import { getMailboxReserve, saveMailboxReserve } from '../src/api/mailboxReserve.js'
import { dialog } from '../src/utils/dialog.js'
vi.mock('../src/api/mailboxReserve.js', () => ({ getMailboxReserve: vi.fn(), saveMailboxReserve: vi.fn() }))
vi.mock('../src/utils/dialog.js', () => ({ dialog: { confirm: vi.fn() } }))
const record = (account = 'a', count = 20) => ({ account_id: account, white_coin_mails: [{ count, coins_per_mail: 90 }], fu_chuan_mail_count: 10, version: 1, updated_at: '2026-10-22T00:00:00Z' })
const deferred = () => { let resolve; const promise = new Promise(r => { resolve = r }); return { promise, resolve } }
let wrapper
const open = async () => { wrapper = mount(MailboxReserve, { props: { userId: 'owner', accountId: 'a' } }); await flushPromises() }
const input = label => wrapper.get(`input[aria-label="${label}"]`)
const submit = async () => { await wrapper.get('form').trigger('submit'); await flushPromises() }
const button = text => wrapper.findAll('button').find(b => b.text() === text)
afterEach(() => wrapper?.unmount())
beforeEach(() => { vi.resetAllMocks(); getMailboxReserve.mockResolvedValue(record()) })
it('读取不写入，折算多行并覆盖保存，清零合法', async () => {
  await open()
  expect(wrapper.text()).toContain('1,800 白金币 · 30 普通符传')
  expect(saveMailboxReserve).not.toHaveBeenCalled()
  await button('添加白金币邮件').trigger('click')
  await input('第2行白金币邮件封数').setValue('2')
  await input('第2行每封白金币').setValue('60')
  await input('符传邮件封数').setValue('20')
  expect(wrapper.text()).toContain('1,920 白金币 · 60 普通符传')
  saveMailboxReserve.mockImplementation(async (account, user, body) => ({ account_id: account, ...body, version: 2, updated_at: '2026-10-22T01:00:00Z' }))
  await submit()
  expect(saveMailboxReserve).toHaveBeenCalledWith('a', 'owner', { expected_version: 1, white_coin_mails: [{ count: 20, coins_per_mail: 90 }, { count: 2, coins_per_mail: 60 }], fu_chuan_mail_count: 20 })
  expect(wrapper.text()).toContain('已保存')
  await submit()
  expect(saveMailboxReserve).toHaveBeenCalledTimes(1)
  await input('符传邮件封数').setValue('0')
  await input('第1行白金币邮件封数').setValue('0')
  await input('第2行白金币邮件封数').setValue('0')
  expect(wrapper.text()).toContain('0 白金币 · 0 普通符传')
  await submit()
  expect(saveMailboxReserve.mock.lastCall[2].expected_version).toBe(2)
})
it('空白负数小数及越界值不提交', async () => {
  await open()
  for (const value of ['', '-1', '0.5', '1000001']) {
    await input('符传邮件封数').setValue(value)
    await submit()
    expect(saveMailboxReserve).not.toHaveBeenCalled()
  }
})
it('读取失败不伪装成零储备，重试不写入', async () => {
  getMailboxReserve.mockRejectedValueOnce(new Error('读取失败'))
  await open()
  expect(wrapper.find('form').exists()).toBe(false)
  expect(wrapper.text()).toContain('读取失败')
  await button('重新读取').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('1,800 白金币')
  expect(saveMailboxReserve).not.toHaveBeenCalled()
})
it('保存失败保留草稿，冲突须确认后重载', async () => {
  await open()
  await input('符传邮件封数').setValue('15')
  saveMailboxReserve.mockRejectedValueOnce(new Error('断网')).mockRejectedValueOnce(Object.assign(new Error('版本冲突'), { status: 409 }))
  await submit()
  expect(input('符传邮件封数').element.value).toBe('15')
  expect(wrapper.text()).toContain('断网')
  await submit()
  expect(wrapper.text()).toContain('版本冲突')
  await submit()
  expect(saveMailboxReserve).toHaveBeenCalledTimes(2)
  dialog.confirm.mockResolvedValueOnce(false)
  await button('重新读取').trigger('click'); await flushPromises()
  expect(input('符传邮件封数').element.value).toBe('15')
  dialog.confirm.mockResolvedValueOnce(true)
  await button('重新读取').trigger('click'); await flushPromises()
  expect(input('符传邮件封数').element.value).toBe('10')
})
it('切换账号和用户忽略迟到读取，空账号不请求', async () => {
  const late = deferred()
  getMailboxReserve.mockReturnValueOnce(late.promise).mockResolvedValueOnce(record('b', 2))
  await open()
  await wrapper.setProps({ accountId: 'b' }); await flushPromises()
  late.resolve(record('a', 99)); await flushPromises()
  expect(wrapper.text()).toContain('180 白金币')
  expect(wrapper.text()).not.toContain('8,910')
  getMailboxReserve.mockResolvedValueOnce(record('b', 3))
  await wrapper.setProps({ userId: 'other' }); await flushPromises()
  expect(getMailboxReserve).toHaveBeenLastCalledWith('b', 'other')
  expect(wrapper.text()).toContain('270 白金币')
  const calls = getMailboxReserve.mock.calls.length
  await wrapper.setProps({ accountId: '' }); await flushPromises()
  expect(wrapper.find('form').exists()).toBe(false)
  expect(getMailboxReserve).toHaveBeenCalledTimes(calls)
})
it('保存中阻止离开，迟到保存不覆盖新账号', async () => {
  await open()
  await input('符传邮件封数').setValue('15')
  const late = deferred()
  saveMailboxReserve.mockReturnValueOnce(late.promise)
  await submit()
  expect(await wrapper.vm.confirmDiscard()).toBe(false)
  getMailboxReserve.mockResolvedValueOnce(record('b', 1))
  await wrapper.setProps({ accountId: 'b' }); await flushPromises()
  late.resolve(record('a', 99)); await flushPromises()
  expect(wrapper.text()).toContain('90 白金币')
  expect(wrapper.text()).not.toContain('8,910')
})
it('未保存离开可取消，刷新保护且卸载清理监听', async () => {
  await open()
  expect(await wrapper.vm.confirmDiscard()).toBe(true)
  await input('符传邮件封数').setValue('15')
  dialog.confirm.mockResolvedValue(false)
  expect(await wrapper.vm.confirmDiscard()).toBe(false)
  const event = new Event('beforeunload', { cancelable: true })
  window.dispatchEvent(event)
  expect(event.defaultPrevented).toBe(true)
  wrapper.unmount(); wrapper = null
  const after = new Event('beforeunload', { cancelable: true })
  window.dispatchEvent(after)
  expect(after.defaultPrevented).toBe(false)
})

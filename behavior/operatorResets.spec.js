import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import Dialog from '../src/components/operator/OperatorResetDialog.vue'
import * as api from '../src/api/operatorResets.js'

vi.mock('../src/api/operatorResets.js', () => ({ previewOperatorReset: vi.fn(), executeOperatorReset: vi.fn(), listOperatorResets: vi.fn(), previewOperatorResetUndo: vi.fn(), undoOperatorReset: vi.fn() }))
const wrappers = []
const preview = () => ({ preview_token: 'preview', before: { op: { level: 40, elite: 2, level_breakthrough_stage: 3 } }, resources: [{ id: 'bingshuquanjuan', count: 65, balance_before: 10, balance_after: 75 }], blockers: [], money: 180000, experience: 65600 })
const record = () => ({ id: 'reset_1', before: preview().before, refunds: { bingshuquanjuan: 65 }, created_at: '2026-10-01T00:00:00Z', undone_at: null })
const deferred = () => { let resolve; const promise = new Promise(yes => { resolve = yes }); return { promise, resolve } }
const render = () => { const wrapper = mount(Dialog, { attachTo: document.body, props: { entry: { id: 'op', name: '测试密探' }, accountId: 'a', accountName: '测试账号', game: '如鸢', userId: 'u' }, global: { stubs: { Teleport: true } } }); wrappers.push(wrapper); return wrapper }
const button = (wrapper, name) => wrapper.findAll('button').find(item => item.text() === name)
beforeEach(() => {
  vi.resetAllMocks()
  api.previewOperatorReset.mockResolvedValue(preview())
  api.listOperatorResets.mockResolvedValue({ items: [], next_cursor: null })
  api.executeOperatorReset.mockResolvedValue(record())
  api.previewOperatorResetUndo.mockResolvedValue({ ...preview(), before: { op: { level: 1, elite: 1, level_breakthrough_stage: 0 } }, resources: [{ id: 'bingshuquanjuan', count: -65, balance_before: 75, balance_after: 10 }] })
  api.undoOperatorReset.mockResolvedValue({ ...record(), undone_at: '2026-10-02T00:00:00Z' })
})
afterEach(() => wrappers.splice(0).forEach(wrapper => wrapper.unmount()))

it('打开和取消不写入，确认前显示账号、练度与库存变化', async () => {
  const w = render(); await flushPromises()
  expect(w.text()).toContain('测试账号')
  expect(w.text()).toContain('40级 / 修为+2 → 1级 / 修为+1')
  expect(w.text()).toContain('库存 10 → 75')
  expect(button(w, '确认记录并增加库存').attributes('disabled')).toBeDefined()
  await button(w, '关闭').trigger('click')
  expect(w.emitted('close')).toHaveLength(1)
  expect(api.executeOperatorReset).not.toHaveBeenCalled()
  expect(api.undoOperatorReset).not.toHaveBeenCalled()
})
it('修改数量须重新预览和核对后才提交，重复点击只请求一次', async () => {
  const w = render(); await flushPromises()
  await w.get('input[type=checkbox]').setValue(true)
  await w.get('#reset-count-bingshuquanjuan').setValue('66')
  expect(w.text()).toContain('清单有修改')
  await w.get('form').trigger('submit')
  expect(api.executeOperatorReset).not.toHaveBeenCalled()
  api.previewOperatorReset.mockResolvedValue({ ...preview(), preview_token: 'updated', resources: [{ id: 'bingshuquanjuan', count: 66, balance_before: 10, balance_after: 76 }] })
  await button(w, '更新预览').trigger('click'); await flushPromises()
  expect(api.previewOperatorReset.mock.lastCall).toEqual([{ account_id: 'a', game: '如鸢', operator_id: 'op', refunds: { bingshuquanjuan: 66 } }, 'u'])
  const task = deferred(); api.executeOperatorReset.mockReturnValue(task.promise)
  await w.get('input[type=checkbox]').setValue(true)
  await w.get('form').trigger('submit'); await w.get('form').trigger('submit')
  expect(api.executeOperatorReset).toHaveBeenCalledTimes(1)
  expect(api.executeOperatorReset.mock.lastCall[0]).toEqual({ account_id: 'a', game: '如鸢', preview_token: 'updated', confirmed_game_preview: true })
  task.resolve(record()); await flushPromises()
  expect(w.emitted('updated')).toHaveLength(1)
})
it('超时锁住正文并使用相同编号和预览原样重试', async () => {
  api.executeOperatorReset.mockRejectedValueOnce(new Error('网络超时'))
  const w = render(); await flushPromises(); await w.get('input[type=checkbox]').setValue(true)
  await w.get('form').trigger('submit'); await flushPromises()
  const original = api.executeOperatorReset.mock.lastCall
  expect(w.get('#reset-count-bingshuquanjuan').attributes('disabled')).toBeDefined()
  expect(w.text()).toContain('结果尚未确认')
  await w.get('form').trigger('submit'); await flushPromises()
  expect(api.executeOperatorReset.mock.lastCall).toEqual(original)
  expect(w.text()).toContain('已记录重置并增加库存')
})
it.each([{ accountId: 'b' }, { game: '代号鸢' }, { userId: 'v' }, { accountId: '' }])('上下文改变后忽略迟到读取并禁止提交 %s', async props => {
  const task = deferred(); api.previewOperatorReset.mockReturnValue(task.promise)
  const w = render(); await w.setProps(props); task.resolve(preview()); await flushPromises()
  expect(w.emitted('close')).toHaveLength(1)
  expect(w.find('form').exists()).toBe(false)
  expect(api.executeOperatorReset).not.toHaveBeenCalled()
})
it('提交中切换账号或卸载不显示旧结果，不刷新新账号', async () => {
  const task = deferred(); api.executeOperatorReset.mockReturnValue(task.promise)
  const w = render(); await flushPromises(); await w.get('input[type=checkbox]').setValue(true); await w.get('form').trigger('submit')
  await w.setProps({ accountId: 'b' }); task.resolve(record()); await flushPromises()
  expect(w.emitted('updated')).toBeUndefined()
  expect(w.text()).not.toContain('已记录重置并增加库存')
})
it('失败保留数量，冲突后必须重新预览', async () => {
  api.executeOperatorReset.mockRejectedValueOnce({ status: 409, message: '库存已变化' })
  const w = render(); await flushPromises(); await w.get('input[type=checkbox]').setValue(true); await w.get('form').trigger('submit'); await flushPromises()
  expect(w.get('#reset-count-bingshuquanjuan').element.value).toBe('65')
  await w.get('input[type=checkbox]').setValue(true); await w.get('form').trigger('submit')
  expect(api.executeOperatorReset).toHaveBeenCalledTimes(1)
  await button(w, '更新预览').trigger('click'); await flushPromises(); await w.get('input[type=checkbox]').setValue(true); await w.get('form').trigger('submit'); await flushPromises()
  expect(api.executeOperatorReset).toHaveBeenCalledTimes(2)
})
it('刷新后从持久记录预览撤销，确认才扣回材料并恢复练度', async () => {
  api.listOperatorResets.mockResolvedValue({ items: [record()], next_cursor: null })
  api.previewOperatorReset.mockRejectedValue({ message: '密探已经是等级1、修为+1' })
  const w = render(); await flushPromises(); await button(w, '撤销本次重置').trigger('click'); await flushPromises()
  expect(w.text()).toContain('1级 / 修为+1 → 40级 / 修为+2')
  expect(w.text()).toContain('库存 75 → 10')
  expect(api.undoOperatorReset).not.toHaveBeenCalled()
  await w.get('form').trigger('submit'); await flushPromises()
  expect(api.undoOperatorReset).toHaveBeenCalledExactlyOnceWith('reset_1', { account_id: 'a', game: '如鸢', preview_token: 'preview' }, 'u')
  expect(w.text()).toContain('原练度已恢复')
})
it('撤销冲突显示原因并保留后续数据', async () => {
  api.listOperatorResets.mockResolvedValue({ items: [record()], next_cursor: null })
  api.previewOperatorResetUndo.mockResolvedValue({ ...preview(), blockers: ['材料 bingshuquanjuan 库存不足，无法扣回 65'] })
  const w = render(); await flushPromises(); await button(w, '撤销本次重置').trigger('click'); await flushPromises()
  expect(w.text()).toContain('材料 兵书全卷 库存不足')
  await w.get('form').trigger('submit')
  expect(api.undoOperatorReset).not.toHaveBeenCalled()
})
it('未知100级经验不会把兵书默认为零，整十级突破必须选择', async () => {
  api.previewOperatorReset.mockResolvedValue({ ...preview(), experience: null, before: { op: { level: 100, elite: 17, level_breakthrough_stage: 9 } }, blockers: ['请核对兵书'] })
  const w = render(); await flushPromises()
  expect(w.get('#reset-count-bingshuquanjuan').element.value).toBe('')
  expect(button(w, '更新预览').attributes('disabled')).toBeDefined()
  expect(w.text()).toContain('兵书经验未核实')
})
it('初次历史迟到不覆盖操作后的记录', async () => {
  const task = deferred(); api.listOperatorResets.mockReturnValueOnce(task.promise).mockResolvedValue({ items: [record()], next_cursor: null })
  const w = render(); await flushPromises(); await w.get('input[type=checkbox]').setValue(true); await w.get('form').trigger('submit'); await flushPromises()
  task.resolve({ items: [], next_cursor: null }); await flushPromises()
  expect(button(w, '撤销本次重置')).toBeDefined()
})

it('更早记录可分页读取，失败后保留已有记录并可重试', async () => {
  api.listOperatorResets.mockResolvedValueOnce({ items: [record()], next_cursor: 'cursor' }).mockRejectedValueOnce(new Error('历史读取失败')).mockResolvedValue({ items: [{ ...record(), id: 'reset_0' }], next_cursor: null })
  const w = render(); await flushPromises()
  await button(w, '更早记录').trigger('click'); await flushPromises()
  expect(w.text()).toContain('历史读取失败')
  expect(w.findAll('article')).toHaveLength(1)
  await button(w, '更早记录').trigger('click'); await flushPromises()
  expect(w.findAll('article')).toHaveLength(2)
  expect(api.listOperatorResets.mock.lastCall).toEqual(['a', '如鸢', 'op', 'u', 'cursor'])
})
